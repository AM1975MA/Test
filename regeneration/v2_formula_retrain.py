#!/usr/bin/env python3
"""ETF V2 125-feature formula migration: strictly paired annual walk-forward.
Comparisons:
  LEGACY: exact source at research-v2-127-allocations-20261020.
  DOWNVOL_ONLY: same legacy kernel, replacing only rolling_downvol().
  CORRECTED: corrected kernel including Wilder RSI, true-NaN fixes etc.
All variants use exact same tickers, raw bytes, eligibility, labels, hyperparameters,
annual folds and model seeds. Source-only XGBoost direct scores: no Tail/Macro/risk.
"""
from __future__ import annotations
import argparse,hashlib,json,sys
from pathlib import Path
import numpy as np
import pandas as pd
from xgboost import XGBRanker

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"regeneration"/"campaign"))
import v2_feature_pruning as benchmarking
from etf_trader.source_only import kernel as new
from etf_trader.source_only import kernel_legacy_frozen_20261020 as legacy
from etf_trader.source_only.raw_io import load_ticker_csv_folder,load_baskets

CANDIDATES=("LEGACY","DOWNVOL_ONLY","CORRECTED")
SEEDS=(101,202,303)
def panel_set(raw,baskets_path):
    assert len(new.F2D_FEATURES)==125 and new.F2D_FEATURES==legacy.F2D_FEATURES
    assert list(new.COMPACT_SEEDS)==list(legacy.COMPACT_SEEDS)==list(SEEDS)
    bsha=hashlib.sha256(Path(baskets_path).read_bytes()).hexdigest()
    assert bsha==benchmarking.BASKET_SHA
    mats,cats,meta=load_ticker_csv_folder(raw)
    assert len(cats)==149
    mats={name:val.loc[val.index>=pd.Timestamp("2011-01-01")] for name,val in mats.items()}
    baskets=load_baskets(baskets_path,cats)
    assert len(baskets)==500 and all(len(b)==24 for b in baskets)
    for mod in (new,legacy):
        mod.ALL_TICKERS=sorted(cats)
        mod.TICKER_CATEGORY=cats
        mod.CATEGORY_TICKERS={c:sorted(t for t in cats if cats[t]==c) for c in sorted(set(cats.values()))}
    dates=legacy.month_end_dates(mats["Close"].index)
    if len(dates) and dates[-1]==mats["Close"].index[-1]:
        dates=dates[:-1]
    _,xlegacy,_,_=legacy.build_features(mats)
    # Retain 100% original labels including sample/execution calendar.
    labelled=legacy.add_labels(xlegacy[xlegacy.signal_date.isin(dates)],mats["Open"],dates)
    original_downvol=legacy.rolling_downvol
    try:
        legacy.rolling_downvol=new.rolling_downvol
        _,xdown,_,_=legacy.build_features(mats)
    finally:
        legacy.rolling_downvol=original_downvol
    _,xcorrect,_,_=new.build_features(mats)
    keys=["signal_date","ticker"]
    base=labelled[keys]
    for label,x in [("DOWNVOL_ONLY",xdown),("CORRECTED",xcorrect)]:
        assert x[keys].equals(base), f"Feature-key row order mismatch: {label}"
    panels={"LEGACY":labelled,"DOWNVOL_ONLY":labelled[keys+[
                c for c in labelled if c not in new.F2D_FEATURES and c not in keys]].merge(
                xdown[keys+new.F2D_FEATURES],on=keys,validate="one_to_one"),
            "CORRECTED":labelled[keys+[
                c for c in labelled if c not in new.F2D_FEATURES and c not in keys]].merge(
                xcorrect[keys+new.F2D_FEATURES],on=keys,validate="one_to_one")}
    for name,p in panels.items():
        assert len(p)==len(labelled),(name,len(p),len(labelled))
        assert not p[keys].duplicated().any()
        pd.testing.assert_frame_equal(p[keys].reset_index(drop=True),base.reset_index(drop=True))
        # Original labels are shared, not regenerated by corrected kernels.
        for target in ["target_rank_21","fwd_ret_21","exit_date_21"]:
            pd.testing.assert_series_equal(p[target],labelled[target],check_names=False)
    feature_evidence=[]
    ref=panels["LEGACY"][new.F2D_FEATURES]
    for name in ["DOWNVOL_ONLY","CORRECTED"]:
        frame=panels[name][new.F2D_FEATURES]
        for col in new.F2D_FEATURES:
            a=ref[col].to_numpy(float)
            b=frame[col].to_numpy(float)
            both=np.isfinite(a)&np.isfinite(b)
            equal=np.isclose(a,b,rtol=1e-12,atol=1e-12,equal_nan=True)
            feature_evidence.append({"variant":name,"feature":col,"n_rows":len(a),
                "changed_fraction":float((~equal).mean()),
                "original_missing":float((~np.isfinite(a)).mean()),
                "updated_missing":float((~np.isfinite(b)).mean()),
                "common_numeric":int(both.sum())})
    return panels,baskets,pd.DataFrame(feature_evidence),meta,bsha

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--raw",default="etf_trader_raw")
    ap.add_argument("--baskets",default="regeneration/SUPER_GOLD_BASKET_MEMBERSHIP.csv")
    ap.add_argument("--years",default="2018,2019,2020")
    ap.add_argument("--variants",default=",".join(CANDIDATES))
    ap.add_argument("--out",default="runs/v2_formula_retrain")
    args=ap.parse_args()
    years=[int(y) for y in args.years.split(",")]
    requested=args.variants.split(",")
    assert years and len(years)==len(set(years)) and set(years)<=set(range(2018,2027))
    assert requested and len(requested)==len(set(requested)) and set(requested)<=set(CANDIDATES)
    assert "LEGACY" in requested
    out=Path(args.out);out.mkdir(parents=True,exist_ok=True)
    panels,baskets,feature_evidence,source,bsha=panel_set(args.raw,args.baskets)
    feature_evidence.to_csv(out/"FEATURE_DELTA.csv",index=False)
    # Common eligibility deliberately uses the frozen LEGACY row mask, not a
    # per-variant recalculation: identical ticker/month panels.
    valid=(panels["LEGACY"][new.F2D_FEATURES].notna().sum(axis=1)>=30)
    assert sum(valid)>0
    cfg=dict(legacy.COMPACT_PARAMS,max_depth=0,grow_policy="lossguide",max_leaves=127)
    assert cfg["objective"]=="rank:pairwise" and cfg["n_estimators"]==360
    records=[];audits=[];predictions=[]
    for year in years:
        cutoff=pd.Timestamp(year,1,1)
        trmask=((panels["LEGACY"].signal_date>=pd.Timestamp("2012-01-01"))&
            (panels["LEGACY"].signal_date<cutoff)&
            (panels["LEGACY"].exit_date_21<cutoff)&
            panels["LEGACY"].target_rank_21.notna()&valid)
        temask=panels["LEGACY"].signal_date.dt.year.eq(year)&valid
        train_base=panels["LEGACY"][trmask].sort_values(["signal_date","ticker"])
        test_base=panels["LEGACY"][temask].sort_values(["signal_date","ticker"])
        assert train_base.signal_date.nunique()>=60
        assert train_base.exit_date_21.max()<cutoff
        assert len(train_base)>0 and len(test_base)>0
        groups=train_base.groupby("signal_date",sort=True).size().to_numpy()
        y=np.rint(100*train_base.target_rank_21.to_numpy(float)).astype(int)
        assert groups.sum()==len(train_base)
        for name in requested:
            tr=panels[name][trmask].sort_values(["signal_date","ticker"])
            te=panels[name][temask].sort_values(["signal_date","ticker"])
            assert train_base[["signal_date","ticker"]].equals(tr[["signal_date","ticker"]])
            assert test_base[["signal_date","ticker"]].equals(te[["signal_date","ticker"]])
            assert tr.target_rank_21.equals(train_base.target_rank_21)
            X=tr[new.F2D_FEATURES].replace([np.inf,-np.inf],np.nan)
            XP=te[new.F2D_FEATURES].replace([np.inf,-np.inf],np.nan)
            ensemble=[]
            for seed in SEEDS:
                learner=XGBRanker(**cfg,random_state=seed)
                learner.fit(X,y,group=groups,verbose=False)
                ensemble.append(learner.predict(XP))
            forecast=te[["signal_date","ticker","fwd_ret_21"]].copy()
            forecast["pred"]=np.mean(ensemble,axis=0)
            for _,one in forecast.groupby("signal_date",sort=True):
                m=benchmarking.eval_month(one,baskets)
                if m is not None:records.append({"variant":name,**m})
            p=forecast.copy()
            p.insert(0,"variant",name)
            predictions.append(p)
            audits.append({"year":year,"variant":name,"train_n":len(tr),"test_n":len(te),
                           "train_months":int(train_base.signal_date.nunique()),
                           "last_mature_label":str(train_base.exit_date_21.max()),
                           "feature_count":len(new.F2D_FEATURES),
                           "train_missing_frac":float(X.isna().to_numpy().mean()),
                           "fitted_seeds":list(SEEDS),"params":cfg})
            print("FIT_DONE",year,name,len(tr),len(te),flush=True)
    monthly=pd.DataFrame(records)
    if monthly.empty:raise RuntimeError("No matured OOS monthly results")
    for name in requested:
        assert monthly.loc[monthly.variant==name].signal_date.tolist()==(
            monthly.loc[monthly.variant=="LEGACY"].signal_date.tolist())
    monthly.to_csv(out/"PAIRED_MONTHLY.csv",index=False)
    pd.concat(predictions,ignore_index=True).to_csv(out/"OOS_SCORES.csv",index=False)
    metrics=["universe_ic","universe_top1","universe_top3","universe_regret",
            "universe_selected_excess","basket_top1","basket_top3","basket_regret",
            "basket_selected_excess"]
    summary=monthly.groupby("variant")[metrics].mean()
    summary.insert(0,"n_months",monthly.groupby("variant").size())
    summary.to_csv(out/"RESULTS.csv")
    (out/"FIT_AUDIT.json").write_text(json.dumps(audits,indent=2,default=str))
    (out/"MANIFEST.json").write_text(json.dumps({
        "status":"RETRAINED_OOS_COMPARISON","variants":requested,"years":years,
        "original_kernel_sha":"351307d549fa70dea70f77cbefddfc24894b6882",
        "source_run":39482809691,"source_raw_artifact":12292840548,
        "canonical_baskets_sha256":bsha,"n_baskets":500,"basket_size":24,"n_tickers":149,
        "shared_eligibility":"legacy original >=30-of-125 nonmissing",
        "shared_labels":"original mature 21D returns for all variants",
        "learner":"XGBRanker 127 leaves 360 estimators three seeds",
        "tail_overlay_risk":False,"independent_holdout":False,
        "note":"Research replay of previously interrogated calendar; model is NOT promoted."
    },indent=2))
    (out/"SUMMARY.md").write_text("# Original vs corrected V2 formulas (paired OOS)\n\n"+
        "No risk/Tail/Macro overlays. Common training and sample eligibility, identical frozen OHLCV.\n\n"+
        summary.round(5).to_markdown()+"\n")
    print("SUMMARY",summary.to_string(),flush=True)

if __name__=="__main__":main()
